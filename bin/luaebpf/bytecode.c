/*
* Prints, as a Lua chunk, what reading or rewriting a binary chunk takes from the lua/ build that
* wrote it: each opcode's number and argument mode, the metamethod events, the instruction layout
* and the chunk format. make builds it with lunatic's _KERNEL configuration and without it, so
* luaebpf rewrites lunatic's chunks for the CLI's Lua and reads its string.dump with the tables of
* each, rather than restating them in Lua.
*/

#include <stdio.h>

#include <lua.h>
#include <lobject.h>
#include <lopcodes.h>
#include <lopnames.h>
#include <lundump.h>
#include <lstate.h>
#include <ltm.h>

#define BYTECODE_FIELD(name)	printf("\t\t%s = %lld,\n", #name, (long long)(name))

static const char *const bytecode_modes[] = {"iABC", "ivABC", "iABx", "iAsBx", "iAx", "isJ"};

static void bytecode_literal(const char *name, const char *s, size_t n)
{
	size_t i;

	printf("\t\t%s = \"", name);
	for (i = 0; i < n; i++)
		printf("\\x%02x", (unsigned char)s[i]);
	printf("\",\n");
}

int main(void)
{
	int op;

	printf("-- auto-generated by bin/luaebpf/bytecode.c, do not edit\n\n");
	printf("return {\n\topcodes = {\n");
	for (op = 0; op < NUM_OPCODES; op++)
		printf("\t\t%s = {op = %d, mode = \"%s\"},\n", opnames[op], op, bytecode_modes[getOpMode(op)]);
	printf("\t},\n\tlayout = {\n");
	BYTECODE_FIELD(POS_OP); BYTECODE_FIELD(SIZE_OP);
	BYTECODE_FIELD(POS_A); BYTECODE_FIELD(SIZE_A); BYTECODE_FIELD(POS_k);
	BYTECODE_FIELD(POS_B); BYTECODE_FIELD(SIZE_B); BYTECODE_FIELD(POS_C); BYTECODE_FIELD(SIZE_C);
	BYTECODE_FIELD(POS_vB); BYTECODE_FIELD(SIZE_vB); BYTECODE_FIELD(POS_vC); BYTECODE_FIELD(SIZE_vC);
	BYTECODE_FIELD(POS_Bx); BYTECODE_FIELD(SIZE_Bx); BYTECODE_FIELD(POS_Ax); BYTECODE_FIELD(SIZE_Ax);
	BYTECODE_FIELD(POS_sJ); BYTECODE_FIELD(SIZE_sJ);
	BYTECODE_FIELD(OFFSET_sBx); BYTECODE_FIELD(OFFSET_sJ); BYTECODE_FIELD(OFFSET_sC);
	/* ltm.c names the events only inside luaT_init, so this spells the enum as ltm.h fences it */
	printf("\t},\n\tevents = {\n");
	BYTECODE_FIELD(TM_INDEX); BYTECODE_FIELD(TM_NEWINDEX); BYTECODE_FIELD(TM_GC);
	BYTECODE_FIELD(TM_MODE); BYTECODE_FIELD(TM_LEN); BYTECODE_FIELD(TM_EQ);
	BYTECODE_FIELD(TM_ADD); BYTECODE_FIELD(TM_SUB); BYTECODE_FIELD(TM_MUL); BYTECODE_FIELD(TM_MOD);
#ifndef _KERNEL
	BYTECODE_FIELD(TM_POW); BYTECODE_FIELD(TM_DIV);
#endif /* _KERNEL */
	BYTECODE_FIELD(TM_IDIV); BYTECODE_FIELD(TM_BAND); BYTECODE_FIELD(TM_BOR); BYTECODE_FIELD(TM_BXOR);
	BYTECODE_FIELD(TM_SHL); BYTECODE_FIELD(TM_SHR); BYTECODE_FIELD(TM_UNM); BYTECODE_FIELD(TM_BNOT);
	BYTECODE_FIELD(TM_LT); BYTECODE_FIELD(TM_LE); BYTECODE_FIELD(TM_CONCAT);
	BYTECODE_FIELD(TM_CALL); BYTECODE_FIELD(TM_CLOSE);
	printf("\t},\n\tformat = {\n");
	bytecode_literal("SIGNATURE", LUA_SIGNATURE, sizeof(LUA_SIGNATURE) - 1);
	bytecode_literal("DATA", LUAC_DATA, sizeof(LUAC_DATA) - 1);
	BYTECODE_FIELD(LUAC_VERSION); BYTECODE_FIELD(LUAC_FORMAT);
	BYTECODE_FIELD(LUAC_INT); BYTECODE_FIELD(LUAC_INST);
#ifndef _KERNEL
	printf("\t\tLUAC_NUM = %.17g,\n\t\tFLOAT = true,\n", (double)LUAC_NUM);
	BYTECODE_FIELD(LUA_VNUMFLT);
#else /* _KERNEL */
	BYTECODE_FIELD(LUAC_NUM);
#endif /* _KERNEL */
	printf("\t\tINT = %zu,\n\t\tINSTRUCTION = %zu,\n\t\tINTEGER = %zu,\n\t\tNUMBER = %zu,\n",
		sizeof(int), sizeof(Instruction), sizeof(lua_Integer), sizeof(lua_Number));
	BYTECODE_FIELD(LUA_VNIL); BYTECODE_FIELD(LUA_VFALSE); BYTECODE_FIELD(LUA_VTRUE);
	BYTECODE_FIELD(LUA_VNUMINT); BYTECODE_FIELD(LUA_VSHRSTR); BYTECODE_FIELD(LUA_VLNGSTR);
	BYTECODE_FIELD(PF_VAHID); BYTECODE_FIELD(PF_VATAB);
	printf("\t},\n}\n\n");
	return 0;
}

